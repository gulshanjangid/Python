a = 20
b = 5

# Arithmetic
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Remainder:", a % b)
print("Power:", a ** b)

# Comparison
print("Equal:", a == b)
print("Not Equal:", a != b)
print("Greater:", a > b)
print("Less:", a < b)

# Logical
print("AND:", a > 10 and b < 10)
print("OR:", a < 10 or b < 10)
print("NOT:", not(a > b))

# Membership
numbers = [10, 20, 30]

print("20 in list:", 20 in numbers)
print("50 not in list:", 50 not in numbers)

# Identity
x = numbers
print("Same object:", x is numbers)
